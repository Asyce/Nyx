// Generate id-indexed weapon art/metadata for the pull tracker from the
// local Nanoka mirror — no network. Output is a small browser global
// (window.NYX_WEAPONS[game]) that the resolver reads alongside the
// character roster (window.CM_CFG). Only weapons whose icon actually
// exists on disk are emitted, so the UI never shows a broken image.
//
// Run: node ./tools/gen-weapons-meta.mjs    (from Site/)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '../..'); // Nyx root
const dbDir = path.resolve(root, 'Database');
const generatedDataDir = path.resolve(root, 'Site', 'src', 'data', 'generated');

const GI_WEAPON_TYPES = {
  WEAPON_SWORD_ONE_HAND: 'Sword',
  WEAPON_CLAYMORE: 'Claymore',
  WEAPON_POLE: 'Polearm',
  WEAPON_BOW: 'Bow',
  WEAPON_CATALYST: 'Catalyst',
};

// Per-game source config. Extend with hsr/zzz/wuwa as their adapters land.
const GAMES = {
  gi:  { src: 'Nanoka/gi/live/weapons.json',     types: GI_WEAPON_TYPES },
  hsr: { src: 'Nanoka/hsr/live/lightcones.json', types: {} }, // Light Cones
  zzz: { src: 'Nanoka/zzz/live/w-engines.json',  types: {} }, // W-Engines
  wuwa: { src: 'Nanoka/ww/live/weapons.json',    types: {} }, // Nyx key is 'wuwa'
};

// Asset field names vary per game/category (weapons, light cones,
// w-engines). Probe in preference order and take the first that exists.
const ART_FIELDS = ['gacha', 'fullFigure', 'full', 'splash', 'mediumIcon', 'medium', 'icon', 'image'];

function buildGame(game, cfg) {
  const srcPath = path.resolve(dbDir, cfg.src);
  const raw = JSON.parse(fs.readFileSync(srcPath, 'utf8'));
  const arr = Array.isArray(raw) ? raw : (raw.weapons || raw.lightcones || raw.list || Object.values(raw));
  const map = {};
  let skipped = 0;
  for (const w of arr) {
    const id = String(w.id || w.Id || '');
    if (!id) continue;
    const assets = w.assets || {};
    let rel = null;
    for (const k of ART_FIELDS) { if (assets[k] && fs.existsSync(path.resolve(dbDir, assets[k]))) { rel = assets[k]; break; } }
    if (!rel) { skipped++; continue; }
    const type = (typeof w.type === 'string') ? (cfg.types[w.type] || w.type) : '';
    map[id] = { name: w.name, rarity: Number(w.rarity) || 0, type: type, art: '../../Database/' + rel };
  }
  return { map, skipped };
}

for (const [game, cfg] of Object.entries(GAMES)) {
  const { map, skipped } = buildGame(game, cfg);
  const body = [
    '// GENERATED by tools/gen-weapons-meta.mjs — do not edit by hand.',
    'window.NYX_WEAPONS = window.NYX_WEAPONS || {};',
    'window.NYX_WEAPONS[' + JSON.stringify(game) + '] = ' + JSON.stringify(map) + ';',
    '',
  ].join('\n');
  fs.mkdirSync(generatedDataDir, { recursive: true });
  fs.writeFileSync(path.resolve(generatedDataDir, `pulls-weapons-${game}.js`), body);
  console.log(`${game}: ${Object.keys(map).length} weapons emitted, ${skipped} skipped (no icon on disk)`);
}
